  (species_no, breed_code, name_bn, name_en, origin_country, breed_kind, is_dual_purpose,
   market_age_days, market_weight_kg, fcr_target,
   mature_weight_male_kg, mature_weight_female_kg,
   age_at_first_egg_days, annual_egg_yield, avg_egg_weight_g,
   lactation_yield_litre, lactation_days, avg_litter_size, note_bn)
select s.species_no, b.breed_code, b.name_bn, b.name_en, b.origin_country, b.breed_kind,
       b.is_dual, b.market_age_days, b.market_weight_kg, b.fcr_target,
       b.mature_m, b.mature_f, b.first_egg_days, b.annual_egg, b.egg_wt,
       b.lact_litre, b.lact_days, b.litter, b.note_bn
from _breed_seed b
join master.species s on s.organization_no is null and s.species_code = b.species_code::citext
where not exists (
  select 1 from master.breed x
   where x.organization_no is null and x.species_no = s.species_no
     and x.breed_code = b.breed_code::citext);

